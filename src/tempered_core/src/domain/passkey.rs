use super::{user::Subject, user_id::UserId};

/// Base64url credential id assigned by the authenticator.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CredentialId(pub String);

impl CredentialId {
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// A registered passkey (WebAuthn credential) belonging to a user.
///
/// `credential_data` is opaque to this crate and owned by the
/// [`WebAuthnVerifier`](crate::WebAuthnVerifier) that produced it: whatever that
/// verifier needs to check a later assertion (a COSE public key, or a whole
/// serialized credential object). Stores persist it verbatim and hand it back.
/// `sign_count` is the authenticator's monotonic counter, used to detect cloned
/// authenticators.
#[derive(Debug, Clone)]
pub struct PasskeyCredential {
    pub credential_id: CredentialId,
    pub credential_data: Vec<u8>,
    pub sign_count: u32,
    /// The account the passkey logs in to (its id: the passkey stays with
    /// the account when its address changes).
    pub owner: UserId,
    /// What the user calls it ("work laptop"), for their list of passkeys.
    pub name: Option<String>,
}

/// Server-generated, single-use handle for one in-flight WebAuthn ceremony.
///
/// It is returned to the client by a `start_*` call and echoed back on the
/// matching `finish_*` call, where it looks up the [`PendingCeremony`]. It is
/// **not** the WebAuthn challenge: that is generated by the verifier and lives
/// inside the ceremony's options and [`CeremonyState`].
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CeremonyId(pub String);

impl CeremonyId {
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Opaque state a [`WebAuthnVerifier`](crate::WebAuthnVerifier) produces when a
/// ceremony starts and needs back to finish it (the challenge it issued, the
/// credentials it allowed, policy flags, …).
///
/// It is kept **server-side** between the two legs and never sent to the
/// client; only the verifier that produced it interprets the bytes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CeremonyState(pub Vec<u8>);

/// What a verifier returns when a ceremony starts.
#[derive(Debug, Clone)]
pub struct CeremonyStart {
    /// The `PublicKeyCredentialCreationOptions` / `…RequestOptions` JSON the
    /// browser passes to `navigator.credentials`.
    pub options: serde_json::Value,
    /// State to keep server-side until the ceremony finishes.
    pub state: CeremonyState,
}

/// Which ceremony a [`PendingCeremony`] is: each `finish_*` accepts only its
/// own, so a login ceremony cannot be finished as an enrolment, or the other
/// way round.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CeremonyKind {
    Registration,
    Authentication,
}

/// An in-flight ceremony as held by a [`ChallengeStore`](crate::ChallengeStore).
#[derive(Debug, Clone)]
pub struct PendingCeremony {
    pub kind: CeremonyKind,
    /// The account the ceremony was started for. Always set for
    /// registration; `None` for a usernameless (discoverable-credential)
    /// authentication.
    pub user: Option<Subject>,
    pub state: CeremonyState,
}

/// What a client receives from a `start_*` call: the options for
/// `navigator.credentials`, plus the handle to send back with the result.
#[derive(Debug, Clone)]
pub struct PasskeyCeremony {
    pub ceremony_id: CeremonyId,
    pub options: serde_json::Value,
}
